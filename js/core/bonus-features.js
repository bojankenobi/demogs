class FreeSpinsManager {
  constructor(wallet, onComplete) {
    this.wallet = wallet;
    this.onComplete = onComplete;

    this.isActive = false;
    this.spinsLeft = 0;
    this.currentMultiplier = 2;
    this.totalWon = 0;

    this.initDOM();
  }

  initDOM() {
    this.hudBanner = document.getElementById('free-spins-hud-banner');
    this.spinsLeftEl = document.getElementById('fs-spins-left');
    this.multiplierEl = document.getElementById('fs-multiplier-val');
    
    this.summaryModal = document.getElementById('fs-summary-modal');
    this.summaryWonEl = document.getElementById('fs-total-won-val');
    this.summaryClaimBtn = document.getElementById('btn-fs-claim');

    if (this.summaryClaimBtn) {
      this.summaryClaimBtn.addEventListener('click', () => {
        if (window.slotAudio) window.slotAudio.playClick();
        this.closeSummary();
      });
    }
  }

  start(spins = 10, startMultiplier = 2) {
    this.isActive = true;
    this.spinsLeft = spins;
    this.currentMultiplier = startMultiplier;
    this.totalWon = 0;

    if (this.wallet) {
      this.wallet.freeSpins = spins;
    }

    document.body.classList.add('free-spins-active');
    if (this.hudBanner) this.hudBanner.style.display = 'flex';
    this.updateHUD();

    if (window.slotAudio) window.slotAudio.playFreeSpinsTrigger();
    if (window.particleEngine) window.particleEngine.spawnCelebration(true);

    if (window.slotApp && window.slotApp.showMessage) {
      window.slotApp.showMessage(`⚡ SUPER BONUS: ${spins} BESPLATNIH SPINOVA (${startMultiplier}x MNOŽILAC)!`, 'jackpot');
    }
  }

  updateHUD() {
    if (this.spinsLeftEl) this.spinsLeftEl.textContent = this.spinsLeft;
    if (this.multiplierEl) this.multiplierEl.textContent = `${this.currentMultiplier}x`;
  }

  onSpinStart() {
    if (!this.isActive) return;
    this.spinsLeft = Math.max(0, this.spinsLeft - 1);
    if (this.wallet) this.wallet.freeSpins = this.spinsLeft;
    this.updateHUD();
  }

  onSpinWin(baseWinAmount) {
    if (!this.isActive || baseWinAmount <= 0) return 0;
    
    // Extra win generated by the multiplier (e.g. at 3x, bonus win is 2x base)
    const multipliedWin = baseWinAmount * this.currentMultiplier;
    this.totalWon += multipliedWin;

    // Progressively increment multiplier for next win
    const nextMultiplier = Math.min(15, this.currentMultiplier + 1);
    if (nextMultiplier > this.currentMultiplier) {
      this.currentMultiplier = nextMultiplier;
      setTimeout(() => {
        if (window.slotAudio) window.slotAudio.playMultiplierUp(this.currentMultiplier);
        this.updateHUD();
        if (window.slotApp && window.slotApp.showMessage) {
          window.slotApp.showMessage(`🔥 MNOŽILAC POVEĆAN NA ${this.currentMultiplier}x!`, 'jackpot');
        }
      }, 350);
    }

    return multipliedWin;
  }

  retrigger(extraSpins = 5) {
    if (!this.isActive) return;
    this.spinsLeft += extraSpins;
    if (this.wallet) this.wallet.freeSpins = this.spinsLeft;
    this.updateHUD();

    if (window.slotAudio) window.slotAudio.playJackpot();
    if (window.particleEngine) window.particleEngine.spawnCelebration(true);
    if (window.slotApp && window.slotApp.showMessage) {
      window.slotApp.showMessage(`🎉 RETRIGGER: +${extraSpins} DODATNIH BESPLATNIH SPINOVA!`, 'jackpot');
    }
  }

  checkCompletion() {
    if (!this.isActive) return false;
    if (this.spinsLeft <= 0) {
      setTimeout(() => this.finish(), 600);
      return true;
    }
    return false;
  }

  finish() {
    this.isActive = false;
    document.body.classList.remove('free-spins-active');
    if (this.hudBanner) this.hudBanner.style.display = 'none';

    if (window.slotApp && window.slotApp.playerTracker) {
      window.slotApp.playerTracker.recordBonus('freeSpins');
    }

    // Open Summary Modal
    if (this.summaryModal && this.summaryWonEl) {
      const denom = (this.wallet && this.wallet.activeDenom) ? this.wallet.activeDenom : 1;
      const rsdTotal = (this.totalWon * denom).toLocaleString();
      this.summaryWonEl.textContent = `+${this.totalWon.toLocaleString()} KREDITA (${rsdTotal} RSD)`;
      this.summaryModal.classList.add('active');
      if (window.slotAudio) window.slotAudio.playBigWinCheer('mega');
      if (window.particleEngine) window.particleEngine.spawnCelebration(true);
    } else {
      if (this.onComplete) this.onComplete(this.totalWon);
    }
  }

  closeSummary() {
    if (this.summaryModal) {
      this.summaryModal.classList.remove('active');
    }
    if (this.onComplete) this.onComplete(this.totalWon);
  }
}

class BigWinCelebrator {
  constructor(wallet) {
    this.wallet = wallet;
    this.isShowing = false;
    this.activeInterval = null;

    this.overlay = document.getElementById('big-win-overlay');
    this.tierTextEl = document.getElementById('big-win-tier-text');
    this.counterEl = document.getElementById('big-win-counter-val');

    if (this.overlay) {
      this.overlay.addEventListener('click', () => this.dismiss());
    }
  }

  trigger(creditsAmount, onComplete) {
    if (this.isShowing || creditsAmount <= 0) {
      if (onComplete) onComplete();
      return;
    }

    const bet = (this.wallet && this.wallet.bet) ? this.wallet.bet : 20;
    const ratio = creditsAmount / bet;
    let tier = 'big';
    let titleText = 'BIG WIN!';

    if (ratio >= 100) {
      tier = 'epic';
      titleText = '💥 EPIC WIN! 💥';
    } else if (ratio >= 50) {
      tier = 'mega';
      titleText = '⭐ MEGA WIN! ⭐';
    } else {
      tier = 'big';
      titleText = '✨ BIG WIN! ✨';
    }

    this.isShowing = true;
    this.onComplete = onComplete;
    this.finalAmount = creditsAmount;

    if (this.tierTextEl) {
      this.tierTextEl.textContent = titleText;
      this.tierTextEl.className = `big-win-banner tier-${tier}`;
    }

    if (this.overlay) this.overlay.classList.add('active');
    if (window.particleEngine) window.particleEngine.spawnCelebration(true);
    if (window.slotAudio) {
      window.slotAudio.playBigWinCheer(tier);
      window.slotAudio.startRollupSound();
    }

    // Roll-up counter animation
    const duration = 2800; // ms
    const startTime = performance.now();

    const updateCounter = (now) => {
      if (!this.isShowing) return;
      const progress = Math.min(1, (now - startTime) / duration);
      // Accelerating ease
      const ease = Math.pow(progress, 1.8);
      const current = Math.floor(this.finalAmount * ease);

      if (this.counterEl) {
        const denom = (this.wallet && this.wallet.activeDenom) ? this.wallet.activeDenom : 1;
        const rsd = (current * denom).toLocaleString();
        this.counterEl.textContent = `${current.toLocaleString()} (${rsd} RSD)`;
      }

      if (progress < 1) {
        requestAnimationFrame(updateCounter);
      } else {
        if (window.slotAudio) window.slotAudio.stopRollupSound();
        // Auto-dismiss after 1.8 seconds if player doesn't click
        this.autoDismissTimer = setTimeout(() => this.dismiss(), 1800);
      }
    };

    requestAnimationFrame(updateCounter);
  }

  dismiss() {
    if (!this.isShowing) return;
    this.isShowing = false;
    if (this.autoDismissTimer) clearTimeout(this.autoDismissTimer);
    if (window.slotAudio) window.slotAudio.stopRollupSound();

    if (this.overlay) this.overlay.classList.remove('active');

    const cb = this.onComplete;
    this.onComplete = null;
    if (cb) cb();
  }
}

class BuyBonusManager {
  constructor(wallet) {
    this.wallet = wallet;
    this.modal = document.getElementById('buy-bonus-modal');
    this.triggerBtn = document.getElementById('btn-buy-bonus');
    this.closeBtn = document.getElementById('buy-bonus-close');

    this.features = {
      wheel: { mult: 45, name: 'Točak Sreće', icon: '🎡' },
      mines: { mult: 35, name: 'IGT Mini-Mines', icon: '💣' },
      freespins: { mult: 50, name: 'Super Besplatni Spinovi', icon: '⚡' }
    };

    this.initEvents();
  }

  initEvents() {
    if (this.triggerBtn) {
      this.triggerBtn.addEventListener('click', () => this.openModal());
    }
    if (this.closeBtn) {
      this.closeBtn.addEventListener('click', () => this.closeModal());
    }
    if (this.modal) {
      this.modal.addEventListener('click', (e) => {
        if (e.target === this.modal) this.closeModal();
      });
    }

    document.querySelectorAll('.btn-confirm-buy').forEach(btn => {
      btn.addEventListener('click', (e) => {
        const feature = btn.getAttribute('data-feature');
        this.executePurchase(feature);
      });
    });
  }

  openModal() {
    if (!this.modal) return;
    this.updatePrices();
    this.modal.classList.add('active');
    if (window.slotAudio) window.slotAudio.playClick();
  }

  closeModal() {
    if (this.modal) this.modal.classList.remove('active');
    if (window.slotAudio) window.slotAudio.playClick();
  }

  updatePrices() {
    const bet = (this.wallet && this.wallet.bet) ? this.wallet.bet : 20;
    const denom = (this.wallet && this.wallet.activeDenom) ? this.wallet.activeDenom : 1;

    Object.keys(this.features).forEach(key => {
      const feat = this.features[key];
      const costCredits = bet * feat.mult;
      const costRsd = +(costCredits * denom).toFixed(2);

      const priceValEl = document.getElementById(`buy-price-val-${key}`);
      const priceBtnEl = document.getElementById(`buy-btn-val-${key}`);

      if (priceValEl) priceValEl.textContent = `${costCredits.toLocaleString()} KR (${costRsd.toLocaleString()} RSD)`;
      if (priceBtnEl) priceBtnEl.textContent = `KUPI ZA ${costRsd.toLocaleString()} RSD`;
    });
  }

  executePurchase(featureType) {
    const feat = this.features[featureType];
    if (!feat) return;

    const bet = (this.wallet && this.wallet.bet) ? this.wallet.bet : 20;
    const denom = (this.wallet && this.wallet.activeDenom) ? this.wallet.activeDenom : 1;
    const costCredits = bet * feat.mult;
    const costRsd = +(costCredits * denom).toFixed(2);

    if (this.wallet.rsdBalance < costRsd) {
      if (window.slotApp) {
        window.slotApp.showMessage('NEMATE DOVOLJNO SREDSTAVA ZA KUPOVINU BONUSA!', 'warning');
      }
      if (window.slotAudio) window.slotAudio.playClick();
      return;
    }

    // Deduct cost from fiat balance
    this.wallet.rsdBalance = +(this.wallet.rsdBalance - costRsd).toFixed(2);
    this.wallet.saveState();
    this.wallet.updateUI();

    if (window.slotAudio) window.slotAudio.playJackpot();
    if (window.particleEngine) window.particleEngine.spawnCelebration(false);

    if (window.slotApp && window.slotApp.playerTracker) {
      window.slotApp.playerTracker.recordBonus(`buy_${featureType}`);
    }

    this.closeModal();

    if (window.slotApp) {
      window.slotApp.showMessage(`⚡ KUPLJEN BONUS: ${feat.name.toUpperCase()} (-${costRsd} RSD)!`, 'jackpot');
    }

    setTimeout(() => {
      if (featureType === 'wheel') {
        if (window.slotApp && window.slotApp.wheelBonus) {
          window.slotApp.wheelBonus.openModal(true);
        }
      } else if (featureType === 'mines') {
        if (window.slotApp && window.slotApp.miniMines) {
          window.slotApp.miniMines.trigger(null, bet);
        }
      } else if (featureType === 'freespins') {
        if (window.slotApp && window.slotApp.freeSpinsManager) {
          window.slotApp.freeSpinsManager.start(10, 2);
        }
      }
    }, 400);
  }
}

window.FreeSpinsManager = FreeSpinsManager;
window.BigWinCelebrator = BigWinCelebrator;
window.BuyBonusManager = BuyBonusManager;
